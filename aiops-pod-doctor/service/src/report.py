"""Turn one RCA report into an e-mail (subject, plain text and HTML).

Everything written by the AI (Grok) is clearly marked as AI-generated: in the subject, in the
summary table, and with BEGIN/END markers around the analysis. Pod details, events and logs are
collected directly from Kubernetes and are labelled as such.
"""

from __future__ import annotations

from email.message import EmailMessage
from html import escape

AI_NOTICE = "AI-generated content: it can be wrong or incomplete; verify before acting."
FACTS_NOTE = "collected from Kubernetes, not AI-generated"


def ai_label(report: dict) -> str:
    if report.get("ai_generated"):
        return f"AI-GENERATED by Grok (model {report.get('ai_model') or 'unknown'})"
    return "rule-based (not AI-generated; Grok was not available)"


def ai_begin(report: dict) -> str:
    return f"----- BEGIN AI-GENERATED CONTENT ({ai_label(report)}) -----\n" if report.get("ai_generated") else ""


def ai_end(report: dict) -> str:
    return "\n----- END AI-GENERATED CONTENT -----" if report.get("ai_generated") else ""


def subject(report: dict) -> str:
    tag = "[AIOps][AI-generated]" if report.get("ai_generated") else "[AIOps]"
    return f"{tag} {report['reason']} in {report['namespace']}/{report['pod']}"


def _summary_rows(report: dict) -> list[tuple[str, str]]:
    return [
        ("Pod", f"{report['namespace']}/{report['pod']}"),
        ("Container", report["container"]),
        ("Failure", report["reason"]),
        ("Status message", report.get("message") or "-"),
        ("Restarts", str(report["restart_count"])),
        ("Detected at", report["time"]),
        ("Analysis", ai_label(report)),
    ]


def render_text(report: dict) -> str:
    rows = "\n".join(f"{name:15} {value}" for name, value in _summary_rows(report))
    return (
        f"AIOps root-cause report\n\n{rows}\n\n"
        + (f"NOTE: {AI_NOTICE}\n\n" if report.get("ai_generated") else "")
        + f"== Analysis: {ai_label(report)} ==\n{ai_begin(report)}{report['analysis']}{ai_end(report)}\n\n"
        f"== Pod details ({FACTS_NOTE}) ==\n{report.get('pod_details', '-')}\n\n"
        f"== Recent events ({FACTS_NOTE}) ==\n{report.get('events', '-')}\n\n"
        f"== Last log lines ({FACTS_NOTE}; secrets masked) ==\n{report.get('log_excerpt', '-')}\n"
    )


def render_html(report: dict) -> str:
    rows = "".join(
        f"<tr><th align='left' style='padding:4px 12px 4px 0'>{escape(name)}</th><td>{escape(value)}</td></tr>"
        for name, value in _summary_rows(report)
    )

    def block(title: str, text: str) -> str:
        return (
            f"<h3>{escape(title)}</h3>"
            f"<pre style='background:#f6f8fa;padding:12px;white-space:pre-wrap'>{escape(text or '-')}</pre>"
        )

    return (
        "<html><body style='font-family:Arial,sans-serif'>"
        f"<h2>AIOps root-cause report: {escape(report['namespace'])}/{escape(report['pod'])}</h2>"
        f"<table>{rows}</table>"
        + _analysis_html(report)
        + block(f"Pod details ({FACTS_NOTE})", report.get("pod_details", ""))
        + block(f"Recent events ({FACTS_NOTE})", report.get("events", ""))
        + block(f"Last log lines ({FACTS_NOTE}; secrets masked)", report.get("log_excerpt", ""))
        + "<p style='color:#666'>Sent by aiops-pod-doctor (Kubernetes CronJob). "
        + escape(
            f"Only the section marked AI-generated was written by Grok; {AI_NOTICE}"
            if report.get("ai_generated")
            else "No AI was used for this report."
        )
        + "</p></body></html>"
    )


def _analysis_html(report: dict) -> str:
    text = escape(report["analysis"] or "-")
    if not report.get("ai_generated"):
        return (
            f"<h3>Analysis ({escape(ai_label(report))})</h3>"
            f"<pre style='background:#f6f8fa;padding:12px;white-space:pre-wrap'>{text}</pre>"
        )
    return (
        "<div style='border:2px solid #d4a72c;background:#fff8c5;padding:12px;margin:12px 0'>"
        f"<p style='margin:0 0 8px 0'><b>&#9888; {escape(ai_label(report))}</b><br>{escape(AI_NOTICE)}</p>"
        f"<pre style='background:#ffffff;padding:12px;white-space:pre-wrap;margin:0'>{text}</pre>"
        "<p style='margin:8px 0 0 0;font-size:12px'>&#8212; end of AI-generated content &#8212;</p></div>"
    )


def build_email(report: dict, sender: str, recipients: tuple[str, ...]) -> EmailMessage:
    message = EmailMessage()
    message["Subject"] = subject(report)
    message["From"] = sender
    message["To"] = ", ".join(recipients)
    message.set_content(render_text(report))
    message.add_alternative(render_html(report), subtype="html")
    return message
